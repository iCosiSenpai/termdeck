#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { loadThemes } from "../src/catalog.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const noticePath = path.join(root, "assets", "wallpapers", "NOTICE.md");

function renderNotice(themes) {
  const core = themes.filter((theme) => theme.category === "core");
  const special = themes.filter((theme) => theme.category === "special");
  const coreRows = core
    .map((theme) => `| ${theme.name} | ${theme.version} | \`${path.basename(theme.wallpaper)}\` | ${theme.provenance.artworkLicense} |`)
    .join("\n");
  const specialSections = special.map((theme) => `### ${theme.name} ${theme.version}

\`${path.basename(theme.wallpaper)}\` is an original AI-assisted, unofficial fan-art composition created for Termdeck and inspired by [*${theme.provenance.property}*](${theme.provenance.sourceUrl}). It is distributed only as part of this free theme project.

**Artwork terms:** ${theme.provenance.artworkLicense}. Do not sell it, imply official affiliation, or reuse it as a standalone commercial asset. *${theme.provenance.property}*, its characters, and associated marks remain the property of ${theme.provenance.rightsHolder}. No endorsement is claimed or implied.`).join("\n\n");

  return `# Wallpaper notice

<!-- Generated by scripts/render-wallpaper-notice.js from themes/*.json. Do not edit manually. -->

Theme provenance is part of the catalog contract. Every theme must declare its artwork origin and terms before \`npm run check\` can pass, so new themes cannot silently bypass this notice.

## Core Collection

The Core wallpapers are original AI-assisted compositions created specifically for Termdeck. They may be redistributed under the terms shown below as part of Termdeck and its theme packages. Do not present the artwork as human-painted or resell it as a standalone stock-art collection.

| Theme | Version | Asset | Artwork license |
| --- | --- | --- | --- |
${coreRows}

Each Core wallpaper is art-directed for terminal use: 16:9 composition, a dark low-detail text field on the left, and visual focus on the right. The canonical generation briefs are recorded in [\`PROMPTS.md\`](PROMPTS.md).

## Special Editions

Special Editions are unofficial fan works and are not covered by the project's MIT License unless their individual entry explicitly says otherwise. Third-party names, characters, marks, and source properties remain with their respective rights holders.

${specialSections}
`;
}

const output = renderNotice(loadThemes());
if (process.argv.includes("--check")) {
  const current = fs.existsSync(noticePath) ? fs.readFileSync(noticePath, "utf8") : "";
  if (current !== output) {
    console.error("assets/wallpapers/NOTICE.md is stale; run npm run notices");
    process.exitCode = 1;
  }
} else {
  fs.writeFileSync(noticePath, output);
  console.log(`rendered ${path.relative(root, noticePath)}`);
}
